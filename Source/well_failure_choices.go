func wellClassifierBranch(equipment string) string {
	v := strings.ToUpper(strings.TrimSpace(equipment))
	switch {
	case strings.Contains(v, "ОРЭ-УШГН"), strings.Contains(v, "УШГН"), strings.Contains(v, "УШВН"), strings.Contains(v, "НПУ"):
		return "УШГН/УШВН/ОРЭ-УШГН"
	case strings.Contains(v, "УЭЦН"), strings.Contains(v, "УЭВН"), strings.Contains(v, "ЭЦН"):
		return "УЭЦН/УЭВН"
	default:
		return ""
	}
}

func wellNodesForEquipment(equipment string) []string {
	v := strings.ToUpper(strings.TrimSpace(equipment))
	switch v {
	case "ЭЦН":
		v = "УЭЦН"
	case "ЭВН":
		v = "УЭВН"
	case "ШГН":
		v = "УШГН"
	case "ШВН":
		v = "УШВН"
	}
	var result []string
	for _, name := range wellNodeChoices {
		if v == "" || strings.HasPrefix(name, v+" | ") {
			result = append(result, name)
		}
	}
	return result
}
