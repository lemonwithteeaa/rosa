func openMethodsReference() {
	if s, ok := methodsSelectedSuggestion(); ok {
		openMethodsReferenceDialog("РОСА — карточка выбранного метода", selectedMethodReferenceText(s))
		return
	}
	openMethodsReferenceDialog("РОСА — справочник методов и расчётов", methodsReferenceMethodsText())
}

func methodProbabilityShort(a MethodEffectAssessment) string {
	if !a.ProbabilityAvailable {
		return "НД"
	}
	return fmt.Sprintf("%d%%", a.EffectProbability)
}

func openMethodsReplication() {
	key := strings.TrimSpace(selectedObjectKey)
	if key == "" {
		msg("Аналоги", "Сначала закрепите объект на Главной.", MB_OK|MB_ICONWARNING)
		return
	}
	var r ReplicationAssessment
	if s, ok := methodsSelectedSuggestion(); ok {
		r = methodReplicationAssessmentForSuggestion(s, key, time.Now())
	} else if d, ok := latestApprovedMethodDecision(key); ok && len(d.Methods) > 0 {
		r = methodReplicationAssessment(key, d.Methods[0], time.Now())
	} else if d, ok := latestApprovedMethodDecision(key); ok && strings.TrimSpace(d.Method) != "" {
		r = methodReplicationAssessment(key, d.Method, time.Now())
	} else {
		msg("Аналоги", "Выберите метод в таблице или сначала утвердите метод/комплекс.", MB_OK|MB_ICONWARNING)
		return
	}
	body := methodsReferenceReplicationText() + "\r\n\r\n" + methodReplicationText(r) + "\r\n\r\n" + learnedExperienceText(key, r.Method)
	openMethodsReferenceDialog("РОСА — аналоги и перенос решения", body)
}
