func mrpAccumulationStatus(r MRPForecastResult) string {
	switch {
	case r.ObservationCount == 0:
		return "ННО ПО УТВЕРЖДЁННОЙ МЕТОДИКЕ: не рассчитана — нет помесячного учёта Ti/O и простоев. СТАТУС ПРОГНОЗА: завершённых циклов нет; текущий МРП — достигнутый возраст, не срок отказа. Откройте «Методика ННО»."
	case r.ObservationCount < 3:
		return fmt.Sprintf("ННО ПО УТВЕРЖДЁННОЙ МЕТОДИКЕ: не рассчитана — нет помесячного учёта Ti/O и простоев. СТАТУС ПРОГНОЗА: %d завершённый(ых) цикл(а); число ниже — предварительный ориентир. Проценты вероятности скрыты, аналоги не проверены по пласту и дебиту. Откройте «Методика ННО».", r.ObservationCount)
	case r.ObservationCount < 5:
		return fmt.Sprintf("ННО ПО УТВЕРЖДЁННОЙ МЕТОДИКЕ: не рассчитана — нет помесячного учёта Ti/O и простоев. СТАТУС ПРОГНОЗА: %d завершённых цикла; база — медиана истории. Скользящее среднее по способу допустимо лишь при 3 сопоставимых циклах. Проценты вероятности скрыты.", r.ObservationCount)
	default:
		return fmt.Sprintf("ННО ПО УТВЕРЖДЁННОЙ МЕТОДИКЕ: не рассчитана — нет помесячного учёта Ti/O и простоев. СТАТУС ПРОГНОЗА: %d завершённых циклов; проценты разрешены только после проверки по времени. Учебные эффекты методов остаются отдельными.", r.ObservationCount)
	}
}

func mrpGuideWndProc(hwnd uintptr, message uint32, wParam, lParam uintptr) uintptr {
	switch message {
	case WM_CREATE:
		parent := syscall.Handle(hwnd)
		header := modalCreate("STATIC", mrpGuideWindowTitle, WS_CHILD|WS_VISIBLE|SS_LEFT, 24, 20, 850, 36, parent, 0)
		if hFontHeaderBold != 0 {
			pSendMessageW.Call(uintptr(header), WM_SETFONT, uintptr(hFontHeaderBold), 1)
		}
		_ = riched20.Load()
		body := modalCreate("RichEdit20W", mrpGuideBody, WS_CHILD|WS_VISIBLE|WS_BORDER|WS_TABSTOP|ES_MULTILINE|ES_AUTOVSCROLL|ES_READONLY|WS_VSCROLL, 24, 65, 850, 560, parent, 0)
		if hFontPanel != 0 {
			pSendMessageW.Call(uintptr(body), WM_SETFONT, uintptr(hFontPanel), 1)
		}
		return 0
	case labMappingClose:
		mrpGuideDone = true
		pDestroyWindowAuth.Call(hwnd)
		return 0
	}
	r, _, _ := pDefWindowProcW.Call(hwnd, uintptr(message), wParam, lParam)
	return r
}

func openMRPAccumulationGuide() {
	openMRPTextDialog("МЕТОДИКА ННО И ПРАВИЛА ПРОГНОЗА", mrpAccumulationGuideText())
}

func openMRPRollingDrill() {
	in, ok := mrpForecastInputForSelectedObject()
	if !ok {
		msg("Проверить расчёт", "Сначала выберите объект.", MB_OK|MB_ICONWARNING)
		return
	}
	openMRPTextDialog("СКОЛЬЗЯЩАЯ НАРАБОТКА · СОСТАВ РАСЧЁТА", mrpRollingDetail(in))
}

func openMRPTextDialog(title, body string) {
	mrpGuideDone = false
	mrpGuideWindowTitle, mrpGuideBody = title, body
	cls := p("ROSAMRPAccumulationGuideV1")
	inst, _, _ := pGetModuleHandleW.Call(0)
	wc := WNDCLASSEX{CbSize: uint32(unsafe.Sizeof(WNDCLASSEX{})), LpfnWndProc: syscall.NewCallback(mrpGuideWndProc), HInstance: syscall.Handle(inst), HbrBackground: syscall.Handle(5 + 1), LpszClassName: cls}
	pRegisterClassExW.Call(uintptr(unsafe.Pointer(&wc)))
	pEnableWindow.Call(uintptr(hMain), 0)
	hwnd, _, _ := pCreateWindowExW.Call(0x00000080, uintptr(unsafe.Pointer(cls)), uintptr(unsafe.Pointer(p("РОСА — "+title))), 0x00CA0000|WS_VISIBLE, 0x80000000, 0x80000000, 916, 690, uintptr(hMain), 0, inst, 0)
	if hwnd == 0 {
		pEnableWindow.Call(uintptr(hMain), 1)
		msg(title, body, MB_OK|MB_ICONINFORMATION)
		return
	}
	var message MSG
	for !mrpGuideDone {
		r, _, _ := pGetMessageW.Call(uintptr(unsafe.Pointer(&message)), 0, 0, 0)
		if int32(r) <= 0 {
			break
		}
		if handleModalEscape(hwnd, &message) {
			continue
		}
		pTranslateMessage.Call(uintptr(unsafe.Pointer(&message)))
		pDispatchMessageW.Call(uintptr(unsafe.Pointer(&message)))
	}
	pEnableWindow.Call(uintptr(hMain), 1)
	pSetFocus.Call(uintptr(hMain))
}
